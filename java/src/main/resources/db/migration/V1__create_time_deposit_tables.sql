-- Tables exactly as the brief defines them.
-- A-6: names are the brief's camelCase, unquoted; PostgreSQL stores them in lower case.
-- A-5: money is NUMERIC(19, 2), two decimal places.

CREATE TABLE timeDeposits (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planType VARCHAR(50)    NOT NULL,
    days     INTEGER        NOT NULL,
    balance  NUMERIC(19, 2) NOT NULL
);

CREATE TABLE withdrawals (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timeDepositId INTEGER        NOT NULL REFERENCES timeDeposits (id),
    amount        NUMERIC(19, 2) NOT NULL,
    date          DATE           NOT NULL
);

-- The list endpoint reads withdrawals per deposit.
CREATE INDEX withdrawals_time_deposit_id_idx ON withdrawals (timeDepositId);
